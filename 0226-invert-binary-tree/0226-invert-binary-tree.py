# Definition for a binary tree node.
# class TreeNode:
#     def __init__(self, val=0, left=None, right=None):
#         self.val = val
#         self.left = left
#         self.right = right
class Solution:
    def invertTree(self, root: Optional[TreeNode]) -> Optional[TreeNode]:
        def invert(curr):
            if curr:
                curr.left, curr.right = invert(curr.right), invert(curr.left)
            return curr

        return invert(root)

